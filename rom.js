const operatorLookup = Object.fromEntries(Object.entries(operators).map(([k, v]) => [v[0], [k, v[1]]]));

const branches = new Set([
  0x90,
  0xb0,
  0xf0,
  0x30,
  0xd0,
  0x10,
  // 0x20, // JSR
]);

const jumps = new Set([
  0x00, // BRK
  0x4c, // JMP
]);

const stops = new Set([
 0x60, // RTS
]);

const code = (v)  => v.toString(16).padStart(2, "0");

const offs = (a) => a - 0xf000;

const romread = (input, a, bc) => {
  const zs = [];

  for (var b=0; b<bc; b++) {
    zs.push(input[offs(a + b)]);
  }

  zs.reverse();

  return zs.reduce((p, c) => (p << 8) + c, 0);
}

const ep = (input) => (romread(input, 0xfffc, 2) & 0xffff) | 0xf000;

const scan = (input) => {
  const entrypoint = ep(input);
  console.log("EP", entrypoint);

  const reachable = new Set([]);

  const follow = (ix, pc) => {
    while (pc <= 0xffff) {
      if (reachable.has(pc)) {
        return;
      }

      const operator = romread(ix, pc, 1);

      if (operator === undefined) {
	console.log("Unknown", pc.toString(16));
	return;
      } else if (!(operator in operatorLookup)) {
	console.log(pc.toString(16));
	console.log("Unknown", "o", operator, "pc", pc.toString(16));
	return;
      }

      reachable.add(pc);

      const [_, l] = operatorLookup[operator];
      const next = pc + l + 1

      if (jumps.has(operator)) {
	const target = romread(ix, pc + 1, l);
	console.log("JMP", pc.toString(16), target.toString(16));
        follow(ix, target);
        break;
      } else if (branches.has(operator)) {
	const relative = next + romread(ix, pc + 1, l)

	const target = pc + relative;

        follow(ix, target);
      } else if (operator === 0x20) {
	const target = romread(ix, pc + 1, l)

        follow(ix, target);	// console.log("JSR", target.toString(16));
      } else if (stops.has(operator)) {
	return;
      }

      pc = next;
    }
  }

  follow(input, entrypoint);

  return reachable;
}


function formatHex(input, columns = 10) {
  const operations = [];

  for (i = 0; i < input.length; i += columns) {
    operations.push(input.slice(i, i + columns).map(v => v.padStart(2, "0")).join(" "));
  }

  return operations.join("\n");
}

function formatASM(line) {
  const [ops, name] = line;

  const codeAsHex = ops.map(c => c.toString(16).padStart(2, "0"));

  const operand = ops.slice(1);

  return [
    codeAsHex.join(" ").padEnd(8, " "),
    name
	  .replace("nnnn", "nn")
	  .replace("dd", "nn")
	  .replace("nn", operand.reverse().map(o => o.toString(16).padStart(2, "0")).join(""))
  ].join(" ");
}

function toASM(input, addr) {
  const pc = offs(addr)
  const operator = input[pc]

  if (!(operator in operatorLookup)) {
    return [[operator], "Unkown"]
  }

  const [name, operandCount] = operatorLookup[parseInt(operator, 10)];

  const operandBytes = [];
  for (i = 0; i < operandCount; i++) {
    operandBytes.push(input[pc + i + 1]);
  }

  return [[operator].concat(operandBytes), name];
}

const decode = (input) => {
  // Mirror memory for small cartridges
  const rom = input.length === 4096 ? input : input.concat(input);


  const reachable = scan(rom);

  const lines = [];
  var data = [];

  const printData = (pc) => {
      return [
	".data",
	[(pc - data.length).toString(16), "...", pc.toString(16)].join(""),
	data.map(c => c.toString(16).padStart(2, "0")).join(" ")
      ].join(" ")
  }

  let pc = ep(rom)

  while (pc <= 0xffff) {
    if (!(reachable.has(pc))) {
       data.push(romread(rom, pc, 1));
       pc++;
       continue;
    }

    if (data.length > 0) {
      lines.push(printData(pc));
      data = [];
    }

    const operator = romread(rom, pc, 1);
    const [_, l] = operatorLookup[operator];

    lines.push([
      pc.toString(16),
      formatASM(toASM(rom, pc))].join(" "));

    pc += l + 1;
  }

  lines.push(printData(0xffff));

  return lines;
}

